_phrases = [(re.compile(re.escape(a)), b) for a, b in PHRASES]


def _case(src, dst):
    if src.isupper() and len(src) > 1:
        return dst.upper()
    if src[0].isupper():
        return dst[0].upper() + dst[1:]
    return dst


def fix_text(s):
    if not s or not isinstance(s, str):
        return s
    for rx, b in _phrases:
        s = rx.sub(b, s)

    def repl(m):
        w = m.group(0)
        r = WORDS.get(w.lower())
        if r:
            w = _case(w, r)
        lw = w.lower()
        if lw in PROPER and w == lw:
            return PROPER[lw]
        if w in ABBR:
            return ABBR[w]
        return w
    return _word_re.sub(repl, s)
